// Generate the set of predefined function names from reference/ecma-376/part1/predefined-functions.txt,
// the names of ECMA-376 Part 1, 18.17.7.1 to 18.17.7.356. Re-run after updating the reference
// file:
//
//   bun scripts/formula/build-functions.ts
//
// Output: packages/core/src/store/formula/predefined-functions.generated.ts. A test keeps the
// output equal to the reference file (`build-functions.test.ts`). The Ecma notice is a `/*!` legal
// comment, as in the preset geometry (`scripts/lib/ecma-legal-comment.ts`).

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ecmaLegalComment } from '../lib/ecma-legal-comment.ts';

const REPO = join(import.meta.dir, '..', '..');
export const SOURCE = join(REPO, 'reference/ecma-376/part1/predefined-functions.txt');
export const OUT = join(REPO, 'packages/core/src/store/formula/predefined-functions.generated.ts');

/** The function names of the reference file, in subclause order. Throws on a gap. */
export function functionNames(text: string): string[] {
  const names: string[] = [];
  for (const line of text.split('\n')) {
    if (line.trim() === '' || line.startsWith('#')) continue;
    const m = /^18\.17\.7\.(\d+) ([A-Z][A-Z0-9.]*)$/.exec(line);
    if (!m || Number(m[1]) !== names.length + 1) throw new Error(`bad line: ${line}`);
    names.push(m[2]!);
  }
  return names;
}

/** The text of the generated module. */
export function generatedModule(text: string): string {
  const names = functionNames(text);
  return [
    '// GENERATED by scripts/formula/build-functions.ts from reference/ecma-376/part1/predefined-functions.txt.',
    '// Do not edit by hand.',
    '',
    ecmaLegalComment(
      `ECMA-376 predefined function names. The names below are the names of the predefined ` +
        `functions of ECMA-376 Part 1, 5th edition (2016), 18.17.7.1 to 18.17.7.${names.length}, ` +
        '(c) Ecma International. They are a derivative work under item (iv) of the Ecma ' +
        'copyright notice, and the Ecma terms below apply to them, not the Apache License of ' +
        '@xlsx-editor.dev/core.'
    ),
    '/** The predefined function names of ECMA-376 Part 1, 18.17.7, in upper case. */',
    'export const PREDEFINED_FUNCTIONS: ReadonlySet<string> = new Set([',
    ...names.map((n) => `  '${n}',`),
    ']);',
    '',
  ].join('\n');
}

if (import.meta.main) writeFileSync(OUT, generatedModule(readFileSync(SOURCE, 'utf8')));
