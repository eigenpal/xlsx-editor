// The security grep from AGENTS.md "Security". Zero hits outside tests is the gate.
// Taken from pptx-editor/scripts/check-security-grep.mjs at 8dc88c4d. XLSX Editor walks every
// package and every example `src` and `app` folder that exists, follows no symbolic link, reads
// JavaScript sources too, and adds sinks: `fontFamily` templates, HTML parsing, host-window
// `open`, `write`, and `location`, and URL sinks (`href`, `src`, `srcdoc`, JSX and Vue bindings)
// that pass only on a line that calls `sanitizeHref`. Comment lines do not count. One generated
// `blob:` URL is the only exception: see `BLOB_DOWNLOAD_FILE`.
import { existsSync, lstatSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

// Sinks that are never allowed on file-derived data.
const PATTERN =
  /innerHTML|outerHTML|insertAdjacentHTML|dangerouslySetInnerHTML|v-html|document\.write|window\.open\(|\b(defaultView|ownerWindow)\.open\(|\b(ownerDocument|document)\.write(ln)?\(|location\.(assign|replace)\(|\b(window|defaultView|ownerWindow)\.location(\.href)?\s*=(?!=)|setHTMLUnsafe|parseHTMLUnsafe|font-family:.*\$\{|fontFamily\s*[=:].*\$\{|createContextualFragment|parseFromString\([^)]*text\/html|new Function\(|\beval\(/;
// URL sinks. A line passes when it calls `sanitizeHref`, as AGENTS.md "Security" requires.
const URL_SINK =
  /\.href\s*=(?!=)|\b\w*(img|image|el|element|node|frame|script|source|video|audio|embed)\.src\s*=(?!=)|\.srcdoc\s*=(?!=)|setAttribute(NS)?\([^)]*['"`](xlink:)?(href|src|srcdoc)['"`]|\b(href|src)=\{|:(href|src)="/i;
const SANITIZED = /\bsanitizeHref\(/;
// A comment that names a sink is not a sink.
const COMMENT = /^\s*(\/\/|\/?\*)/;
const isHit = (line) =>
  !COMMENT.test(line) && (PATTERN.test(line) || (URL_SINK.test(line) && !SANITIZED.test(line)));
// The only exception to the URL sink rule: `sanitizeHref` drops a `blob:` URL, and a download of
// generated bytes needs one. `BLOB_DOWNLOAD_SINK` passes only in `BLOB_DOWNLOAD_FILE`, and only
// while the code of that file is exactly `BLOB_DOWNLOAD_CODE`, in this order. That code makes one
// object URL from its `Blob` parameter and gives it to one new link. Only whole-line `//` comments
// and blank lines can differ. CRLF line ends pass, because a checkout can convert them and CRLF
// ends a line in the same place as LF. A lone CR, U+2028, or U+2029 refuses the file, because each
// one can end a `//` comment and hide code from this comparison.
const BLOB_DOWNLOAD_FILE = join('examples', 'vite', 'src', 'download.ts');
const BLOB_DOWNLOAD_SINK = "link.setAttribute('href', objectUrl);";
const BLOB_DOWNLOAD_CODE = [
  'export function downloadBlob(blob: Blob, name: string): void {',
  'const objectUrl = URL.createObjectURL(blob);',
  "const link = document.createElement('a');",
  BLOB_DOWNLOAD_SINK,
  'link.download = name;',
  'link.click();',
  'setTimeout(() => URL.revokeObjectURL(objectUrl), 1000);',
  '}',
];
// Why the file is not the permitted code, or null when it is.
const blobDownloadProblem = (text) => {
  const lines = text.replace(/\r\n/g, '\n');
  if (/[\r\u2028\u2029]/.test(lines))
    return 'the file holds a lone CR, U+2028, or U+2029, which can hide code after a `//` comment';
  const code = lines.split('\n').flatMap((line, i) => {
    const trimmed = line.trim();
    return trimmed === '' || trimmed.startsWith('//') ? [] : [{ text: trimmed, at: i + 1 }];
  });
  const end = BLOB_DOWNLOAD_CODE.length;
  for (let i = 0; i < end; i++) {
    if (!code[i]) return `the code ends before the permitted line "${BLOB_DOWNLOAD_CODE[i]}"`;
    if (code[i].text !== BLOB_DOWNLOAD_CODE[i])
      return `line ${code[i].at} is "${code[i].text}", but the permitted line is "${BLOB_DOWNLOAD_CODE[i]}"`;
  }
  return code[end] ? `line ${code[end].at} adds code after the permitted code` : null;
};
const BLOB_DOWNLOAD_REMEDY =
  'Restore the code of the file to `BLOB_DOWNLOAD_CODE` in `scripts/check-security-grep.mjs`, or remove the URL sink.';
const hits = [];
const notes = [];
function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (name === 'node_modules' || name === 'dist' || name === '__tests__') continue;
    const stat = lstatSync(p);
    // A symbolic link is never followed, so a link loop cannot hang the walk.
    if (stat.isSymbolicLink()) continue;
    if (stat.isDirectory()) walk(p);
    else if (
      /\.(ts|tsx|vue|js|mjs|cjs|jsx)$/.test(name) &&
      !/\.(test|spec)\./.test(name) &&
      !name.endsWith('.generated.ts')
    ) {
      const text = readFileSync(p, 'utf8');
      const problem = p === BLOB_DOWNLOAD_FILE ? blobDownloadProblem(text) : undefined;
      const before = hits.length;
      text.split('\n').forEach((line, i) => {
        if (isHit(line) && !(problem === null && line.trim() === BLOB_DOWNLOAD_SINK))
          hits.push(`${p}:${i + 1}: ${line.trim()}`);
      });
      if (problem && hits.length > before)
        notes.push(
          `${p}: the generated blob: URL exception does not apply: ${problem}.`,
          BLOB_DOWNLOAD_REMEDY
        );
    }
  }
}
walk('packages');
if (existsSync('examples')) {
  for (const name of readdirSync('examples')) {
    for (const dir of ['src', 'app'])
      if (existsSync(join('examples', name, dir))) walk(join('examples', name, dir));
  }
}
if (hits.length) {
  console.error(`Security grep: ${hits.length} hit(s)\n${[...hits, ...notes].join('\n')}`);
  process.exit(1);
}
console.log('Security grep: 0 hits');
